plugins {
    id("net.neoforged.moddev")
    id("neoforge-mutex")
    id("com.modrinth.minotaur")
    id("net.darkhax.curseforgegradle")
}

val loader = "neoforge"
val modId = property("mod.id") as String
val modName = property("mod.name") as String
val modVersion = property("mod.version") as String
val modAuthor = property("mod.author") as String
val modLicense = property("mod.license") as String
val modCredits = property("mod.credits") as String
val modDescription = property("mod.description") as String
val modrinthProjectId = property("publish.modrinth") as String
val curseforgeProjectId = property("publish.curseforge") as String
// Every Minecraft version this jar supports, e.g. [1.21.6, 1.21.7, 1.21.8], and their label, e.g. 1.21.6-1.21.8
val mcReleases: List<String> = sc.properties.rawOrNull("mod", "mc_releases")?.asList().orEmpty().map { it.toString() }
val mcLabel = if (mcReleases.size == 1) mcReleases.first() else "${mcReleases.first()}-${mcReleases.last()}"
val requiredJava = when {
    sc.current.parsed >= "26.1" -> JavaVersion.VERSION_25
    sc.current.parsed >= "1.20.5" -> JavaVersion.VERSION_21
    else -> JavaVersion.VERSION_17
}
// Mixin's compatibility level; JAVA_21 also covers the Java 25 versions
val mixinJava = if (requiredJava == JavaVersion.VERSION_17) "JAVA_17" else "JAVA_21"
val neoforgeVersion = property("deps.neoforge") as String
val neoforgeLoaderRange = property("deps.neoforge_loader_range") as String

// Full version, used for the jar name, mod metadata and upload titles: 1.3.1+neoforge-26.3
version = "$modVersion+$loader-$mcLabel"
base.archivesName = modId

neoForge {
    version = neoforgeVersion
    runs {
        configureEach {
            systemProperty("neoforge.enabledGameTestNamespaces", modId)
        }
        register("client") {
            client()
            gameDirectory = file("runs/client")
        }
        register("server") {
            server()
            gameDirectory = file("runs/server")
        }
    }
    mods {
        register(modId) {
            sourceSet(sourceSets.main.get())
        }
    }
}

dependencies {
    testImplementation("org.junit.jupiter:junit-jupiter:5.7.1")
    testRuntimeOnly("org.junit.platform:junit-platform-launcher")
}

java {
    withSourcesJar()
    toolchain.languageVersion = JavaLanguageVersion.of(requiredJava.majorVersion)
}

tasks {
    processResources {
        val props = mapOf(
            "version" to version.toString(),
            "mod_id" to modId,
            "mod_name" to modName,
            "mod_author" to modAuthor,
            "license" to modLicense,
            "credits" to modCredits,
            "description" to modDescription,
            "neoforge_version" to neoforgeVersion,
            // The mod icon key was renamed from logoFile to iconFile in 26.3
            "logo_key" to if (sc.current.parsed >= "26.3") "iconFile" else "logoFile",
            "neoforge_loader_version_range" to neoforgeLoaderRange,
            "mixin_java" to mixinJava,
            // [1.21.6] or [1.21.6,1.21.8]
            "minecraft_version_range" to if (mcReleases.size == 1) "[${mcReleases.first()}]" else "[${mcReleases.first()},${mcReleases.last()}]",
        )
        inputs.properties(props)
        filesMatching(listOf("META-INF/neoforge.mods.toml", "pack.mcmeta", "*.mixins.json")) { expand(props) }
        // NeoForge reads META-INF/mods.toml before 1.20.5
        if (sc.current.parsed < "1.20.5") {
            filesMatching("META-INF/neoforge.mods.toml") { path = "META-INF/mods.toml" }
        }
        exclude("fabric.mod.json")
    }

    // Minecraft sources for the node must be generated by Stonecutter first
    named("createMinecraftArtifacts") {
        dependsOn("stonecutterGenerate")
    }

    jar {
        from(rootProject.file("LICENSE")) { rename { "${it}_$modName" } }
        manifest.attributes(
            "Specification-Title" to modName,
            "Specification-Vendor" to modAuthor,
            "Specification-Version" to archiveVersion,
            "Implementation-Title" to loader,
            "Implementation-Version" to archiveVersion,
            "Implementation-Vendor" to modAuthor,
            "Built-On-Minecraft" to sc.current.version,
        )
    }

    named<Jar>("sourcesJar") {
        from(rootProject.file("LICENSE")) { rename { "${it}_$modName" } }
    }

    test {
        useJUnitPlatform()
        maxHeapSize = "1G"
    }

    // Collects the mod jar into build/release at the root, for the release workflow
    register<Copy>("buildAndCollect") {
        group = "build"
        from(jar.flatMap { it.archiveFile })
        into(rootProject.layout.buildDirectory.dir("release"))
    }
}

// Publishing, run by the release workflow (.github/workflows/release.yml)
// The full changelog lives on the Fabric upload; NeoForge only points there.
val releaseNotesPointer = "Same changes as the Fabric release $modVersion."

modrinth {
    token = System.getenv("MODRINTH_TOKEN")
    projectId = modrinthProjectId
    versionNumber = version.toString()
    versionName = "$modName $version"
    versionType = "release"
    uploadFile.set(tasks.jar)
    gameVersions.set(mcReleases)
    loaders.set(listOf(loader))
    changelog = releaseNotesPointer
}

tasks.register<net.darkhax.curseforgegradle.TaskPublishCurseForge>("curseforge") {
    apiToken = System.getenv("CURSEFORGE_TOKEN")
    val mainFile = upload(curseforgeProjectId, tasks.jar)
    mainFile.displayName = "$modName $version"
    mainFile.releaseType = "release"
    mainFile.changelog = releaseNotesPointer
    mainFile.changelogType = "markdown"
    mainFile.addModLoader("NeoForge")
    mcReleases.forEach { mainFile.addGameVersion(it) }
    mainFile.addJavaVersion("Java ${requiredJava.majorVersion}")
}
